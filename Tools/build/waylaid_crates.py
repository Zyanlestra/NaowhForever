"""Build what each Waylaid Crate can be filled with, from the game's own tables (Tools/sources/wago.py).

A labelled crate ("Waylaid Crate: Apprentice Herbs") is used through its Stock Crate spell
(ItemXItemEffect -> ItemEffect.SpellID), whose description lists the bundles it takes, one a
line: "- $M3 Peacebloom". $Mn is the base points of the spell's nth effect (SpellEffect at
EffectIndex n - 1), so for spell 1247426 that line is 20 Peacebloom. Each name is matched to
exactly one item in ItemSparse, leaving out the items the game marks deprecated (Flags_0 bit
0x10: the old Dark Iron Ore, 11099, beside the real one, 11370). A name that matches no item
or more than one, an option line that does not read, or a crate with no list stops the build,
so a change in the game's tables is caught here, not in game.

Left out: the unlabelled Waylaid Crate (its spell only reads the label, the crate it becomes
is the labelled one), and the Waylaid Supplies, which each take one fixed item ("Add $q2
Copper Bars to complete the shipment."), so there is nothing to choose between.

Writes NaowhForever_QoL/Loot/WaylaidCratesData.lua: crate item ID -> { { item ID, count }, ... }
in the game's own order, which Auction Prices prices on the crate's tooltip. Names are matched
here only; the addon reads IDs, so it works in every client language. Run it again when
wago.BUILD moves on.

Usage: python Tools/build/waylaid_crates.py [--build 1.60.1.70862]
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
import wago  # noqa: E402
from journal import header, write  # noqa: E402

ROOT = paths.ROOT
OUT = ROOT / "NaowhForever_QoL" / "Loot" / "WaylaidCratesData.lua"

CRATE = "Waylaid Crate: "        # a labelled crate's name starts so
DEPRECATED = 0x10                # ItemSparse.Flags_0: a deprecated item
BASE_DIFFICULTY = "0"            # SpellEffect.DifficultyID of a spell's own effects
OPTION = re.compile(r"^- \$M(\d+) (.+?)(?:\|r)?$")
COLUMNS = {
    "ItemSparse": ("ID", "Display_lang", "Flags_0"),
    "ItemXItemEffect": ("ItemID", "ItemEffectID"),
    "ItemEffect": ("ID", "SpellID"),
    "Spell": ("ID", "Description_lang"),
    "SpellEffect": ("SpellID", "EffectIndex", "EffectBasePointsF", "DifficultyID"),
}


def item_ids(sparse):
    """Item name -> the IDs of the items of that name, deprecated items left out."""
    ids = {}
    for row in sparse:
        if not int(row["Flags_0"]) & DEPRECATED:
            ids.setdefault(row["Display_lang"], []).append(int(row["ID"]))
    return ids


def fillings(spell, description, points, ids):
    """The (item ID, count) bundles a Stock Crate spell's description lists, in its order."""
    found = []
    for line in description.split("\n"):
        line = line.strip()
        if not line.startswith("-"):
            continue
        match = OPTION.match(line)
        if not match:
            sys.exit(f"spell {spell}: cannot read the line {line!r}")
        effect, name = int(match.group(1)), match.group(2)
        count = points.get((spell, effect - 1))
        if not count:
            sys.exit(f"spell {spell}: effect {effect} has no count for {name}")
        matches = ids.get(name, [])
        if len(matches) != 1:
            sys.exit(f"spell {spell}: {name!r} is {len(matches)} items {sorted(matches)}, not one")
        found.append((matches[0], count))
    return found


def crates(tables):
    """Crate item ID -> its bundles, for every labelled Waylaid Crate."""
    sparse = tables["ItemSparse"]
    ids = item_ids(sparse)
    names = {int(row["ID"]): row["Display_lang"] for row in sparse if row["Display_lang"].startswith(CRATE)}
    spell_of = {row["ID"]: int(row["SpellID"]) for row in tables["ItemEffect"]}
    spells = {}
    for row in tables["ItemXItemEffect"]:
        if int(row["ItemID"]) in names:
            spells.setdefault(int(row["ItemID"]), []).append(spell_of[row["ItemEffectID"]])
    descriptions = {int(row["ID"]): row["Description_lang"] for row in tables["Spell"]}
    points = {(int(row["SpellID"]), int(row["EffectIndex"])): int(float(row["EffectBasePointsF"]))
              for row in tables["SpellEffect"] if row["DifficultyID"] == BASE_DIFFICULTY}
    found = {}
    for crate, name in names.items():
        lists = [fillings(spell, descriptions.get(spell, ""), points, ids) for spell in spells.get(crate, [])]
        lists = [bundles for bundles in lists if bundles]
        if len(lists) != 1:
            sys.exit(f"{name} ({crate}): {len(lists)} spells list its bundles, not one")
        found[crate] = lists[0]
    return found


def lua(found, build):
    lines = header(OUT.name, "what each Waylaid Crate can be filled with, by item ID, generated by "
                             f"Tools/build/waylaid_crates.py from build {build}")
    lines.append("ns.WaylaidCrates = {")
    for crate in sorted(found):
        bundles = ", ".join(f"{{ {item}, {count} }}" for item, count in found[crate])
        lines.append(f"    [{crate}] = {{ {bundles} }},")
    lines.append("}")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build", default=wago.BUILD)
    build = parser.parse_args().build
    tables = {name: wago.table(name, build) for name in COLUMNS}
    for name, columns in COLUMNS.items():
        rows = tables[name]
        if not rows or any(column not in rows[0] for column in columns):
            sys.exit(f"wago.tools cannot read {name} for {build} yet")
    found = crates(tables)
    write(OUT, lua(found, build))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(found)} crates, "
          f"{sum(len(bundles) for bundles in found.values())} bundles")


if __name__ == "__main__":
    main()
