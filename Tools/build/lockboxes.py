"""Build the Lockpicking skill each lockbox needs, from the game's own tables (Tools/sources/wago.py).

An item with a lock names it in ItemSparse's LockID. A Lock row lists up to eight ways to open
it (Type_N, _Index_N, Skill_N); a skill entry (Type 2) on lock type 1 is Pick Lock, and its
Skill_N is the Lockpicking it needs. Every item whose lock has one is listed, but for:

- items the game flags as deprecated (ItemSparse's Flags_0 bit 0x10: Deprecated Test Strongbox),
- locks above TOP_SKILL, the most Lockpicking a rogue reaches ([DNT] Super Strong Lockbox at 305,
  Rogue's Diary at 5000): test items no player picks.

Read for wago.BUILD with its hotfixes. Writes NaowhForever_QoL/Loot/LockboxData.lua. Run it
again when wago.BUILD moves on.

Usage: python Tools/build/lockboxes.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
import wago  # noqa: E402

OUT = paths.ROOT / "NaowhForever_QoL" / "Loot" / "LockboxData.lua"
SKILL, PICK_LOCK = 2, 1   # a Lock entry's Type for a skill, and the lock type Pick Lock opens
SLOTS = 8                 # entries per Lock row
DEPRECATED = 0x10         # ItemSparse Flags_0
TOP_SKILL = 300           # Lockpicking at level 60, five a level


def pick_skills(locks):
    """Lock ID -> the Lockpicking its Pick Lock entry needs, for each lock that has one."""
    found = {}
    for lock in locks:
        for i in range(SLOTS):
            if int(lock[f"Type_{i}"]) == SKILL and int(lock[f"_Index_{i}"]) == PICK_LOCK:
                found[int(lock["ID"])] = int(lock[f"Skill_{i}"])
                break
    return found


def lockboxes(items, locks):
    """Item ID -> the Lockpicking it needs, for every item a rogue can pick."""
    skills = pick_skills(locks)
    found = {}
    for item in items:
        skill = skills.get(int(item["LockID"] or 0))
        if skill is None or skill > TOP_SKILL or int(item["Flags_0"]) & DEPRECATED:
            continue
        found[int(item["ID"])] = skill
    return found


def render(boxes, build):
    lines = [
        f"-- LockboxData.lua: the Lockpicking skill each lockbox needs (ns.LockboxSkills), generated by "
        f"Tools/build/lockboxes.py from build {build}.",
        "local ns = _G.NaowhForever",
        "",
        "ns.LockboxSkills = {",
    ]
    for item, skill in sorted(boxes.items()):
        lines.append(f"    [{item}] = {skill},")
    lines.extend(["}", ""])
    return "\r\n".join(lines)


def main():
    boxes = lockboxes(wago.table("ItemSparse"), wago.table("Lock"))
    OUT.write_text(render(boxes, wago.BUILD), encoding="ascii", newline="")
    print(f"{len(boxes)} lockboxes -> {OUT.relative_to(paths.ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
