"""Build NaowhForever_Professions/Data/EnchantSlots.lua: the gear each Enchanting recipe goes on.

From the Forever client's own tables, through the project's wago reader for wago.BUILD with its
hotfixes: every Enchanting (skill line 333) ability in SkillLineAbility that has a
SpellEquippedItems row, with that row's item class, inventory type mask and subclass mask, as the
game checks them on the item the enchant is cast on. Recipes that make an item (oils, rods, wands)
have no such row and are left out. Cached in data/enchant_slots.json; --offline rebuilds from it.

Usage: python Tools/build/enchant_slots.py [--offline]
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
import wago  # noqa: E402

OUT = paths.ROOT / "NaowhForever_Professions" / "Data" / "EnchantSlots.lua"
CACHE = paths.DATA / "enchant_slots.json"
ENCHANTING = 333


def read_rows(abilities, equipped):
    """Spell ID (as text) -> [item class, inventory type mask, subclass mask] for each Enchanting
    ability the game limits to some gear."""
    spells = {row["Spell"] for row in abilities if int(row["SkillLine"]) == ENCHANTING}
    found = {}
    for row in equipped:
        if row["SpellID"] in spells:
            found[row["SpellID"]] = [int(row["EquippedItemClass"]), int(row["EquippedItemInvTypes"]),
                                     int(row["EquippedItemSubclass"])]
    return found


def load_rows(offline):
    if offline:
        return json.loads(CACHE.read_text(encoding="utf-8"))
    rows = read_rows(wago.table("SkillLineAbility"), wago.table("SpellEquippedItems"))
    CACHE.write_text(json.dumps(rows, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    return rows


def render(rows):
    lines = [
        "-- EnchantSlots.lua: the gear each Enchanting recipe goes on, generated by Tools/build/enchant_slots.py.",
        "local P = _G.NaowhForever.Professions",
        "",
        "P.EnchantSlots = {",
    ]
    for spell in sorted(rows, key=int):
        item_class, inv, sub = rows[spell]
        lines.append(f"    [{spell}] = {{ {item_class}, {inv}, {sub} }},")
    lines.extend(["}", ""])
    return "\r\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    rows = load_rows(args.offline)
    OUT.write_text(render(rows), encoding="utf-8", newline="")
    print(f"{len(rows)} enchants -> {OUT.name}", file=sys.stderr)


if __name__ == "__main__":
    main()
