"""Build the world map's zone level ranges.

Forever's client tables have no level range for an outdoor zone (UiMap and AreaTable carry no
ContentTuningID for them), so C_Map.GetMapLevels has nothing to give and the world map never
shows one. Wowhead's world map for Forever lists each zone's range ("places", kind "zone",
with its uiMapID and a "levels" string such as "30-44"), and that is what is written here.
A zone Wowhead gives no range (Moonglade, Mount Hyjal, Shen'dralas) is left out.

Writes NaowhForever_QoL/Interface/ZoneLevelsData.lua.

Usage: python Tools/build/zone_levels.py
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402,F401
from journal import ROOT, header, write  # noqa: E402
from wowhead import WOWHEAD, fetch  # noqa: E402
from zone_exits import page_data  # noqa: E402

OUT = ROOT / "NaowhForever_QoL" / "Interface" / "ZoneLevelsData.lua"
RANGE = re.compile(r"^(\d+)\s*\D\s*(\d+)$")


def zones(node, found):
    if isinstance(node, dict):
        if node.get("kind") == "zone" and node.get("uiMap") and node.get("levels"):
            found[int(node["uiMap"])] = (node["name"], node["levels"])
        for value in node.values():
            zones(value, found)
    elif isinstance(node, list):
        for value in node:
            zones(value, found)
    return found


def main():
    page = fetch(f"{WOWHEAD}/world-map")
    url = re.search(r'https://nether\.wowhead\.com/forever/data/world-map\?[^"\']+', page).group(0)
    places = page_data(fetch(url.replace("&amp;", "&")))["wow.worldMap.classicplus.places"]

    lines = header("ZoneLevelsData.lua", "each zone's level range, generated by Tools/build/zone_levels.py")
    lines.append("ns.ZoneLevels = {")
    for map_id, (name, levels) in sorted(zones(places, {}).items()):
        m = RANGE.match(levels.strip())
        if not m:
            sys.exit(f"cannot read the levels {levels!r} of {name}")
        low, high = int(m.group(1)), int(m.group(2))
        lines.append(f"    [{map_id}] = {{ {low}, {high} }},")
    lines.append("}")
    write(OUT, lines)
    print(f"{len(lines) - 5} zones -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
